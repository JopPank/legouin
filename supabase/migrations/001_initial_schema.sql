    (4, 'Couple 4');

create table public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    full_name text not null,
    couple_id smallint not null references public.couples (id)
);

create table public.meal_plan (
    id bigint generated by default as identity primary key,
    day_number integer not null check (day_number > 0),
    meal_type text not null check (meal_type in ('Breakfast', 'Lunch', 'Dinner', 'Snacks')),
    assigned_couple_id smallint references public.couples (id),
    menu_details text,
    updated_at timestamptz not null default now(),
    unique (day_number, meal_type)
);

create table public.gear_checklist (
    id bigint generated by default as identity primary key,
    item_name text not null check (length(trim(item_name)) > 0),
    category text not null,
    is_communal boolean not null default true,
    claimed_by_user uuid references public.profiles (id) on delete set null,
    is_packed boolean not null default false
);

create table public.expenses (
    id bigint generated by default as identity primary key,
    description text not null check (length(trim(description)) > 0),
    amount numeric(10, 2) not null check (amount > 0),
    paid_by_user uuid references public.profiles (id) on delete set null,
    split_type text not null default 'equal' check (split_type = 'equal'),
    created_at timestamptz not null default now()
);

create or replace function public.is_trip_participant()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.profiles
        where id = (select auth.uid())
    );
$$;

revoke all on function public.is_trip_participant() from public, anon;
grant execute on function public.is_trip_participant() to authenticated;

create or replace function public.guard_gear_claim()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if tg_op = 'INSERT' then
        if new.claimed_by_user is not null and new.claimed_by_user <> (select auth.uid()) then
            raise exception 'Gear can only be claimed for the signed-in participant.';
        end if;
    elsif new.claimed_by_user is distinct from old.claimed_by_user then
        if old.claimed_by_user is not null and old.claimed_by_user <> (select auth.uid()) then
            raise exception 'Only the participant who claimed this item can release it.';
        end if;
        if new.claimed_by_user is not null and new.claimed_by_user <> (select auth.uid()) then
            raise exception 'Gear can only be claimed for the signed-in participant.';
        end if;
    end if;
    return new;
end;
$$;

create trigger guard_gear_claim
before insert or update of claimed_by_user on public.gear_checklist
for each row execute function public.guard_gear_claim();

