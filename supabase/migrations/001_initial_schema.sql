create policy "Participants can read couples"
on public.couples for select to authenticated
using ((select public.is_trip_participant()));

create policy "Participants can read trip profiles"
on public.profiles for select to authenticated
using ((select public.is_trip_participant()));

create policy "Participants can update their own name"
on public.profiles for update to authenticated
using (id = (select auth.uid()))
with check (id = (select auth.uid()));

create policy "Participants can manage meals"
on public.meal_plan for all to authenticated
using ((select public.is_trip_participant()))
with check ((select public.is_trip_participant()));

create policy "Participants can read gear"
on public.gear_checklist for select to authenticated
using ((select public.is_trip_participant()));

create policy "Participants can add gear"
on public.gear_checklist for insert to authenticated
with check ((select public.is_trip_participant()));

create policy "Participants can update gear"
on public.gear_checklist for update to authenticated
using ((select public.is_trip_participant()))
with check ((select public.is_trip_participant()));

create policy "Participants can read expenses"
on public.expenses for select to authenticated
using ((select public.is_trip_participant()));

create policy "Participants can add their own expenses"
on public.expenses for insert to authenticated
with check (
    (select public.is_trip_participant())
    and paid_by_user = (select auth.uid())
);

create policy "Participants can remove their own expenses"
on public.expenses for delete to authenticated
using (
    (select public.is_trip_participant())
    and paid_by_user = (select auth.uid())
);

