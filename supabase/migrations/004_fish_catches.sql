create table public.fish_catches (
    id bigint generated by default as identity primary key,
    species text not null check (length(trim(species)) > 0),
    weight_kg numeric(6, 2) check (weight_kg is null or weight_kg > 0),
    location text not null default '',
    caught_by_couple_id smallint references public.couples (id),
    released boolean not null default false,
    created_by_user uuid not null default auth.uid() references public.profiles (id),
    created_at timestamptz not null default now()
);

alter table public.fish_catches enable row level security;

create policy "Participants can manage fish catches"
on public.fish_catches for all to authenticated
using ((select public.is_trip_participant()))
with check ((select public.is_trip_participant()));

revoke all on public.fish_catches from anon, authenticated;
grant select, insert, update, delete on public.fish_catches to authenticated;
grant usage, select on sequence public.fish_catches_id_seq to authenticated;

alter table public.fish_catches replica identity full;
alter publication supabase_realtime add table public.fish_catches;
