create policy "Participants can view trip photos"
on storage.objects for select to authenticated
using (
    bucket_id = 'trip-photos'
    and (select public.is_trip_participant())
);

create policy "Participants can upload their own trip photos"
on storage.objects for insert to authenticated
with check (
    bucket_id = 'trip-photos'
    and (select public.is_trip_participant())
    and (storage.foldername(name))[1] = (select auth.uid())::text
);

create policy "Participants can delete their own trip photos"
on storage.objects for delete to authenticated
using (
    bucket_id = 'trip-photos'
    and (select public.is_trip_participant())
    and (storage.foldername(name))[1] = (select auth.uid())::text
);
